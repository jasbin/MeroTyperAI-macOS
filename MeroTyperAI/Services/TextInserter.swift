import AppKit
import Carbon.HIToolbox

/// Types text into the focused app by pasting it, then puts the user's clipboard back.
/// Pasting works in every app, including web and Electron ones that ignore Accessibility text APIs.
@MainActor
enum TextInserter {
    enum Outcome { case typed, copied }

    /// Apps read the pasteboard a moment after ⌘V, so the old clipboard returns only after this.
    private static let restoreDelay: Duration = .seconds(1)
    private static var pendingRestore: Task<Void, Never>?

    static func insert(_ text: String) async -> Outcome {
        // A back-to-back dictation must not snapshot the previous one's text as the user's clipboard.
        await pendingRestore?.value
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)
        write(text, to: pasteboard)
        // Password fields turn on secure input, which blocks synthetic keystrokes. The text stays copied instead.
        guard AXIsProcessTrusted(), !IsSecureEventInputEnabled() else { return .copied }
        let ours = pasteboard.changeCount
        pressCommandV()
        pendingRestore = Task {
            try? await Task.sleep(for: restoreDelay)
            // Keep anything the user copied in the meantime.
            if NSPasteboard.general.changeCount == ours { restore(saved, to: .general) }
            pendingRestore = nil
        }
        return .typed
    }

    static func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private static func write(_ text: String, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Asks clipboard managers to leave this out of their history (nspasteboard.org).
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            Dictionary(item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }) { first, _ in first }
        }
    }

    private static func restore(_ items: [[NSPasteboard.PasteboardType: Data]], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        pasteboard.writeObjects(items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        })
    }

    /// Tags this app's own keystrokes, so the hotkey monitor doesn't read them as the user typing.
    nonisolated static let syntheticMarker: Int64 = 0x4D45_524F

    /// Types into the focused field without touching the clipboard. Used by live typing.
    static func type(_ text: String) {
        let units = Array(text.utf16)
        var start = 0
        while start < units.count {
            // Apps drop longer strings from one event. Never split a surrogate pair.
            var end = min(start + 20, units.count)
            if end < units.count, UTF16.isLeadSurrogate(units[end - 1]) { end -= 1 }
            let chunk = Array(units[start..<end])
            press(0) { $0.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk) }
            start = end
        }
    }

    /// One Delete per character the user sees, which is how text fields count Backspace.
    static func deleteBackward(_ count: Int) {
        for _ in 0..<max(count, 0) { press(CGKeyCode(kVK_Delete)) }
    }

    private static func pressCommandV() {
        press(keyCode(producing: "v") ?? CGKeyCode(kVK_ANSI_V), flags: .maskCommand)
    }

    /// Flags are set explicitly: a held right ⌘ dictation key must not turn typed letters into shortcuts.
    private static func press(_ key: CGKeyCode, flags: CGEventFlags = [], configure: (CGEvent) -> Void = { _ in }) {
        let source = CGEventSource(stateID: .privateState)
        for isDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: isDown) else { continue }
            event.flags = flags
            event.setIntegerValueField(.eventSourceUserData, value: syntheticMarker)
            configure(event)
            event.post(tap: .cghidEventTap)
        }
    }

    /// The key that types `character` with ⌘ held in the current layout, so paste works on Dvorak and the like.
    static func keyCode(producing character: Character) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let layoutData = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(layoutData).takeUnretainedValue() as Data
        let target = Array(String(character).utf16)
        return data.withUnsafeBytes { raw -> CGKeyCode? in
            guard let layout = raw.bindMemory(to: UCKeyboardLayout.self).baseAddress else { return nil }
            for code in 0..<128 {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(
                    layout, UInt16(code), UInt16(kUCKeyActionDown), UInt32((cmdKey >> 8) & 0xFF), UInt32(LMGetKbdType()),
                    OptionBits(1 << kUCKeyTranslateNoDeadKeysBit), &deadKeys, chars.count, &length, &chars
                )
                if status == noErr, Array(chars.prefix(length)) == target { return CGKeyCode(code) }
            }
            return nil
        }
    }
}
